"""
build_data.py - turn product records (JSON lines) into the product table the Seller Revenue pages use.

The repository ships EXAMPLE data only: data/example/onbuy_example_products_raw.jsonl, generated by
tools/gen_example_data.py and calibrated on aggregate statistics (seller_growth/calibration_stats.json).
No raw marketplace data is included.

    python build_data.py      # rebuilds seller_growth/example_products.csv from the example records
"""
from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

import pandas as pd

HERE = Path(__file__).parent
EXAMPLE_RAW = HERE.parent / "data" / "example" / "onbuy_example_products_raw.jsonl"
EXAMPLE_OUT = HERE / "example_products.csv"
SCRAPE_DATE = date(2026, 11, 11)      # snapshot month the example data represents


def orders_k(text) -> float | None:
    """'44k+' -> 44.0 (thousands of lifetime seller orders, as OnBuy shows them)."""
    if not text:
        return None
    m = re.match(r"([\d.]+)k", str(text))
    return float(m.group(1)) if m else None


def _has(notes: str, *words) -> bool:
    return any(w in notes for w in words)


try:
    from .categories import CATEGORIES as _CATS
except ImportError:
    from categories import CATEGORIES as _CATS
SUB_TO_PAGE = {s: k for k, c in _CATS.items() for s in c.subcategories}


def build_products(raw_path: Path) -> pd.DataFrame:
    """Turn product records (one JSON object per line) into the product table used by revenue.py.
    Flag columns are derived from each record's notes."""
    rows = []
    for line in Path(raw_path).read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        dist = {int(k): int(v) for k, v in (r.get("rating_dist") or {}).items()}
        n = sum(dist.values())
        notes = (r.get("notes") or "").lower()
        offers = r.get("offers") or []
        prices = [float(p) for _, p in offers] or [float(r["price"])]
        latest = r.get("delivery_latest")
        orders = r.get("seller_orders")
        rows.append({
            "product_id": r["pid"], "marketplace": r["marketplace"], "category": r["category"],
            "page_category": SUB_TO_PAGE.get(r["subcategory"], ""),
            "subcategory": r["subcategory"], "title": r["title"], "brand": r.get("brand") or "",
            "price": float(r["price"]), "rrp": r.get("rrp"), "delivery_fee": float(r.get("delivery_fee") or 0.0),
            "seller": r.get("seller") or "",
            "seller_professional": bool(r.get("seller_professional")),
            "seller_orders_k": orders_k(orders) if orders and "k" in str(orders) else
                               (float(orders) / 1000 if orders else None),
            "seller_review_count": r.get("seller_review_count"),
            "offers_count": len(offers) if offers else 0,
            "offer_prices": ";".join(f"{p:.2f}" for p in prices),
            "offer_sellers": ";".join(s for s, _ in offers),
            "offer_seller_reviews": ";".join("" if x is None else str(int(x)) for x in (r.get("offer_seller_reviews") or [])),
            "other_sellers": ";".join(s for s, _ in offers[1:]),
            # Professional Seller tag per offer, where recorded (1/0; blank = not recorded, buy-box tag still used)
            "offer_professional": ";".join(str(int(bool(x))) for x in (r.get("offer_professional") or [])),
            "product_review_count": int(r.get("product_review_count") or 0),
            "avg_rating": round(sum(k * v for k, v in dist.items()) / n, 2) if n else None,
            "latest_review": r.get("latest_review") or "",
            # oldest review date, only where the page listed every review (else blank)
            "first_review": r.get("first_review") or "",
            # oldest review visible when the page did NOT list every review: a lower bound on the review window
            "oldest_visible_review": r.get("oldest_visible_review") or "",
            "badge": r.get("rank") or "",
            "in_stock": bool(r.get("in_stock")),
            "max_qty_selectable": r.get("max_qty"),
            "delivery_max_days": (date.fromisoformat(latest) - SCRAPE_DATE).days if latest else None,
            "flag_no_brand": not re.search(r"[A-Za-z]", str(r.get("brand") or "")),
            "flag_duplicate_page": _has(notes, "duplicate"),
            "flag_placeholder_ean": _has(notes, "placeholder ean"),
            "flag_thin_content": _has(notes, "garbled", "mismatched", "templated", "one-line", "broken spacing", "empty"),
            "flag_overseas_dispatch": _has(notes, "overseas"),
            "flag_reviews_from_former_seller": _has(notes, "no longer listed", "former seller"),
            "flag_price_anomaly": _has(notes, "price anomaly"),
            "flag_out_of_stock": not bool(r.get("in_stock")),
            "listing_notes": r.get("notes") or "",
            "url": r["url"], "scrape_date": r["scrape_date"], "method": r["method"],
        })
    return pd.DataFrame(rows)


if __name__ == "__main__":
    df = build_products(EXAMPLE_RAW)
    df.to_csv(EXAMPLE_OUT, index=False)
    print(f"Wrote {EXAMPLE_OUT.name} ({len(df)} example products, {df['page_category'].nunique()} categories)")
